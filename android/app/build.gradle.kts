// Release signing config, loaded from android/key.properties (gitignored —
// see android/.gitignore). Generate your own keystore and key.properties
// per https://flutter.dev/to/reference-keystore; falls back to the debug
// keystore only when key.properties is missing, so `flutter run --release`
// still works without one, but that build must never be distributed.
